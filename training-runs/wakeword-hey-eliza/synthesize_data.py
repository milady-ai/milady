#!/usr/bin/env python3
"""Synthesize positive ("hey eliza") and negative wake-word training clips
using the locally-built llama-omnivoice-server.

This is the synthetic-data path for the wake-word head trainer. Positives are
generated by speaking "hey eliza" with prosody / voice variations; negatives
are generated by speaking short distractor phrases that should never trigger
the wake word. All clips are written as 16 kHz mono PCM16 WAVs (the format
the trainer's `read_wav_pcm16_mono` expects), trimmed to a fixed window.

The output directory layout:
  <out>/positives/         many "hey eliza" wavs (training)
  <out>/heldout-positives/ ~20 "hey eliza" wavs (eval, distinct seeds)
  <out>/negatives/         distractor wavs (training)
  <out>/heldout-negatives/ ~20 distractor wavs (eval, distinct seeds)
  <out>/manifest.json      provenance: phrase, voice/seed grid, sample count

Provenance is captured in manifest.json so reviewers can audit the chain.
"""

