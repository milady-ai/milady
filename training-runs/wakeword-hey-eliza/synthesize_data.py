def have_ffmpeg() -> bool:
    return shutil.which("ffmpeg") is not None


def synth_one(text: str, instruct: str, seed: int, out_wav: Path, *, lang: str = "English") -> bool:
    """Run llama-omnivoice-server once. Returns True on success."""
    out_wav.parent.mkdir(parents=True, exist_ok=True)
    env = os.environ.copy()
    env["LD_LIBRARY_PATH"] = (
        f"{OMNIVOICE_LIBS}:" + env.get("LD_LIBRARY_PATH", "")
    )
    cmd = [
        str(OMNIVOICE_BIN),
        "--model", str(TTS_MODEL),
        "--codec", str(TTS_CODEC),
        "--lang", lang,
        "--instruct", instruct,
        "--seed", str(seed),
        "-o", str(out_wav),
    ]
    try:
        proc = subprocess.run(
            cmd,
            input=text.encode("utf-8"),
            env=env,
            capture_output=True,
            timeout=90,
        )
    except subprocess.TimeoutExpired:
        return False
    if proc.returncode != 0:
        sys.stderr.write(
            f"[synth] failed text={text!r} seed={seed} rc={proc.returncode}\n"
            f"  stderr tail: {proc.stderr.decode('utf-8', errors='replace')[-400:]}\n"
        )
        return False
    return out_wav.is_file() and out_wav.stat().st_size > 1000


def downsample_to_16k_mono(src: Path, dst: Path) -> bool:
    """OmniVoice produces 24 kHz mono WAV; the trainer needs 16 kHz mono PCM16.
    Use ffmpeg to resample. Returns True on success."""
    proc = subprocess.run(
        [
            "ffmpeg", "-y", "-loglevel", "error",
            "-i", str(src),
            "-ar", str(TARGET_SAMPLE_RATE),
            "-ac", "1",
            "-sample_fmt", "s16",
            str(dst),
        ],
        capture_output=True,
    )
    if proc.returncode != 0:
        sys.stderr.write(
            f"[ffmpeg] failed src={src} rc={proc.returncode}\n"
            f"  stderr: {proc.stderr.decode('utf-8', errors='replace')[-400:]}\n"
        )
        return False
    return dst.is_file()


def pad_or_trim(wav_path: Path, target_seconds: float = 2.0) -> None:
    """Pad with silence (or trim) so every clip is the same duration.

    openWakeWord trainer slides a 16-embedding window. A clip < ~1.4s yields
    zero windows. We pad to 2.0s so the head sees at least a few windows per
    clip, with the phrase centered.
    """
    target_samples = int(target_seconds * TARGET_SAMPLE_RATE)
    with wave.open(str(wav_path), "rb") as w:
        if w.getframerate() != TARGET_SAMPLE_RATE or w.getnchannels() != 1 or w.getsampwidth() != 2:
            raise RuntimeError(
                f"{wav_path}: not 16 kHz mono PCM16 — was "
                f"{w.getframerate()}Hz/{w.getnchannels()}ch/{w.getsampwidth()*8}bit"
            )
        frames = w.readframes(w.getnframes())
        n = w.getnframes()
    if n >= target_samples:
        # Center-trim: keep the middle target_samples.
        start = (n - target_samples) // 2
        frames = frames[start * 2 : (start + target_samples) * 2]
    else:
        # Center-pad with silence: half before, half after.
        pad = target_samples - n
        pre = pad // 2
        post = pad - pre
        frames = b"\x00\x00" * pre + frames + b"\x00\x00" * post
    with wave.open(str(wav_path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(TARGET_SAMPLE_RATE)
        w.writeframes(frames)


def synth_clip(
    text: str,
    instruct: str,
    seed: int,
    final_path: Path,
    *,
    tmp_dir: Path,
    target_seconds: float = 2.0,
) -> bool:
    raw_wav = tmp_dir / f"raw-{seed:06d}.wav"
    if not synth_one(text, instruct, seed, raw_wav):
        return False
    if not downsample_to_16k_mono(raw_wav, final_path):
        raw_wav.unlink(missing_ok=True)
        return False
    raw_wav.unlink(missing_ok=True)
    try:
        pad_or_trim(final_path, target_seconds=target_seconds)
    except Exception as exc:
        sys.stderr.write(f"[pad] failed {final_path}: {exc}\n")
        final_path.unlink(missing_ok=True)
        return False
    return True


def synthesize_set(
    out_dir: Path,
    *,
    phrases: list[str],
    instructs: list[str],
    count: int,
    seed_base: int,
    label: str,
    tmp_dir: Path,
) -> int:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = 0
    target = count
    seed_iter = seed_base
    attempts = 0
    max_attempts = target * 3
    while written < target and attempts < max_attempts:
        attempts += 1
        text = phrases[attempts % len(phrases)]
        instruct = instructs[attempts % len(instructs)]
        out = out_dir / f"{label}-{written:05d}.wav"
        if synth_clip(text, instruct, seed_iter, out, tmp_dir=tmp_dir):
            written += 1
            if written % 10 == 0 or written == 1:
                print(f"[synth:{label}] wrote {written}/{target}")
        seed_iter += 1
    if written < target:
        sys.stderr.write(
            f"[synth:{label}] WARN: only wrote {written}/{target} after {attempts} attempts\n"
        )
    return written


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", type=Path, required=True)
    ap.add_argument("--positive-count", type=int, default=300)
    ap.add_argument("--negative-count", type=int, default=300)
    ap.add_argument("--heldout-positive-count", type=int, default=20)
    ap.add_argument("--heldout-negative-count", type=int, default=20)
    ap.add_argument("--target-seconds", type=float, default=2.0)
    args = ap.parse_args(argv)

    if not have_ffmpeg():
        sys.stderr.write("ffmpeg not on PATH; install it (this script needs resampling).\n")
        return 2
    if not OMNIVOICE_BIN.is_file():
        sys.stderr.write(f"OmniVoice binary missing at {OMNIVOICE_BIN}\n")
        return 2
    if not TTS_MODEL.is_file() or not TTS_CODEC.is_file():
        sys.stderr.write("OmniVoice gguf/codec missing — check eliza-1 bundle install.\n")
        return 2

    out_dir = args.out_dir.resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    tmp_dir = out_dir / "_tmp"
    tmp_dir.mkdir(parents=True, exist_ok=True)

    positives_dir = out_dir / "positives"
    negatives_dir = out_dir / "negatives"
    heldout_pos_dir = out_dir / "heldout-positives"
    heldout_neg_dir = out_dir / "heldout-negatives"

    started = datetime.now(timezone.utc).isoformat()

    n_pos = synthesize_set(
        positives_dir,
        phrases=["hey eliza"],
        instructs=INSTRUCTS,
        count=args.positive_count,
        seed_base=1000,
        label="pos",
        tmp_dir=tmp_dir,
    )
    n_neg = synthesize_set(
        negatives_dir,
        phrases=DISTRACTOR_PHRASES,
        instructs=INSTRUCTS,
        count=args.negative_count,
        seed_base=20000,
        label="neg",
        tmp_dir=tmp_dir,
    )
    n_hpos = synthesize_set(
        heldout_pos_dir,
        phrases=["hey eliza"],
        instructs=INSTRUCTS,
        count=args.heldout_positive_count,
        seed_base=50000,
        label="hpos",
        tmp_dir=tmp_dir,
    )
    n_hneg = synthesize_set(
        heldout_neg_dir,
        phrases=DISTRACTOR_PHRASES,
        instructs=INSTRUCTS,
        count=args.heldout_negative_count,
        seed_base=70000,
        label="hneg",
        tmp_dir=tmp_dir,
    )

    finished = datetime.now(timezone.utc).isoformat()

    shutil.rmtree(tmp_dir, ignore_errors=True)

    manifest = {
        "phrase": "hey eliza",
        "started": started,
        "finished": finished,
        "ttsBackend": {
            "tool": "llama-omnivoice-server (eliza-fused fork)",
            "binary": str(OMNIVOICE_BIN),
            "model": str(TTS_MODEL),
            "codec": str(TTS_CODEC),
            "sourceRepo": "elizaOS/llama.cpp (eliza-fused fork)",
            "modelSource": "Serveurperso/OmniVoice-GGUF (Apache-2.0)",
            "outputSampleRateHz": 24000,
            "resampledToHz": TARGET_SAMPLE_RATE,
        },
        "counts": {
            "positives": n_pos,
            "negatives": n_neg,
            "heldoutPositives": n_hpos,
            "heldoutNegatives": n_hneg,
        },
        "voiceInstructs": INSTRUCTS,
        "distractorPhrases": DISTRACTOR_PHRASES,
        "targetSeconds": args.target_seconds,
        "license": {
            "OmniVoice": "Apache-2.0",
            "syntheticAudio": "derived from OmniVoice (Apache-2.0); head is redistributable",
        },
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"[synth] wrote manifest -> {out_dir / 'manifest.json'}")
    print(f"[synth] DONE pos={n_pos} neg={n_neg} hpos={n_hpos} hneg={n_hneg}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
